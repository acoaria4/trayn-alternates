function watch(page) {
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('response', response => { if (response.status() >= 400) failedResponses.push(`${response.status()} ${response.url()}`); });
}
async function jump(page, selector) {
  await page.locator(selector).evaluate(element => element.scrollIntoView({ behavior: 'instant', block: 'start' }));
  await page.waitForTimeout(1100);
}
async function reveal(page) {
  for (const selector of ['#intention', '#object', '#details', '.vision', '#development', '.closing', '.footer']) await jump(page, selector);
}
